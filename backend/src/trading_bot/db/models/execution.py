"""Orders, fills and positions.

Orders carry a ``client_order_id`` unique per mode and run: that uniqueness
constraint is the duplicate-order protection required by the safety rules. A
retry after a timeout reuses the same id, so the database refuses to create a
second order.

``mode`` (PAPER / LIVE / BACKTEST) is on every row here. Paper, live and
replayed results must never be summed together, and the column makes that
mistake impossible to make silently. ``backtest_run_id`` does the same between
two backtests, which share a mode - see ``db.models.backtest``.

Two of the old ``mode``-keyed unique constraints have nullable key columns
(``execution_intent_id``/``signal_leg``, ``attempt_id``), and every order
written before Phase 8's remediation has NULL intent keys. Adding a nullable
run column to them with ``NULLS NOT DISTINCT`` would suddenly make those
legacy rows collide, so each became two partial unique indexes instead - one
for rows outside any run, one per run - which keeps their exact semantics.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    false,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from trading_bot.db.base import Base, RecordMixin
from trading_bot.db.models.backtest import (
    BACKTEST_MODE_HAS_RUN,
    RUN_KEY_MATCHES_RUN,
    backtest_run_fk,
    run_key_column,
    run_key_target,
    run_scoped_fk,
)
from trading_bot.db.models.enum_types import (
    EXECUTION_MODE,
    ORDER_STATUS,
    ORDER_TYPE,
    POSITION_STATUS,
    SIDE,
    TIME_IN_FORCE,
)
from trading_bot.db.models.enums import (
    ExecutionMode,
    OrderStatus,
    OrderType,
    PositionStatus,
    Side,
    TimeInForce,
)
from trading_bot.db.models.market import Market
from trading_bot.db.models.research import STRATEGY_NAME_LENGTH, Signal
